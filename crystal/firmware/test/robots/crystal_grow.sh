#!/bin/sh
# Link test for the L32R literal reach: build the whole firmware with the
# Crystal code stub-grown by about KIB KiB (default 120) of never-executed
# functions full of 32-bit constants (each an L32R literal), so .text is far
# past the 256 KiB that one .literal section can serve. Builds a copy of
# crystal/firmware, so the checkout and its build/ are untouched.
#   [KIB=120] [CRYSTAL_OPT=--release] [CRYSTAL_SPLIT=1] \
#     crystal/firmware/test/robots/crystal_grow.sh
# With CRYSTAL_SPLIT=0 the link is expected to fail ("dangerous relocation:
# l32r: literal target out of range"). Prints the Crystal object's sizes and
# the firmware's memory use (idf.py size). Never flash the result.
set -eu
HERE=$(cd "$(dirname "$0")/../.." && pwd)
KIB=${KIB:-120}
export CRYSTAL_OPT=${CRYSTAL_OPT:---release}
export CRYSTAL_SPLIT=${CRYSTAL_SPLIT:-1}
export WORK=${WORK:-/build/crystal-grow}
ROOTFS=${ROOTFS:-/opt/debian}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
mkdir "$TMP/fw"
cp -a "$HERE/CMakeLists.txt" "$HERE/build.sh" "$HERE/sdkconfig.defaults" "$HERE/partitions.csv" \
      "$HERE/main" "$HERE/src" "$TMP/fw/"
[ -d "$HERE/components" ] && cp -a "$HERE/components" "$TMP/fw/"
rm -f "$TMP/fw/main/crystal_flags.cmake"

# ~13 bytes per statement (l32r + xor + s32i + a 4-byte literal); 100 per function.
FNS=$((KIB * 1024 / 1300 + 1))
awk -v fns="$FNS" 'BEGIN {
  srand(1)
  print "# Generated by test/robots/crystal_grow.sh: never-executed padding."
  print "module Pad"
  for (f = 0; f < fns; f++) {
    print "  @[NoInline]"
    printf "  def self.f%d(p : UInt32*, x : UInt32) : Nil\n", f
    for (j = 0; j < 100; j++)
      printf "    p[%d] = x ^ 0x%08x_u32\n", j, int(rand() * 4294967295)
    print "  end"
  }
  print "  def self.run : Nil"
  print "    p = LibIDF.heap_caps_malloc(400_u32, 0x404_u32).as(UInt32*)"
  print "    x = LibIDF.esp_timer_get_time.to_u32!"
  for (f = 0; f < fns; f++) printf "    f%d(p, x)\n", f
  print "  end"
  print "end"
}' > "$TMP/fw/src/pad.cr"
# Call it behind a condition the compiler can't fold, so nothing is dropped.
sed -i 's/^require "\.\/rt"$/&\nrequire ".\/pad"/' "$TMP/fw/src/main.cr"
sed -i '/^fun crystal_app_main : Void$/a\  Pad.run if LibIDF.esp_timer_get_time < 0_i64' "$TMP/fw/src/main.cr"
grep -q '^require "./pad"' "$TMP/fw/src/main.cr"
grep -q 'Pad.run' "$TMP/fw/src/main.cr"

echo "crystal_grow: +$KIB KiB ($FNS functions), CRYSTAL_OPT='$CRYSTAL_OPT' CRYSTAL_SPLIT=$CRYSTAL_SPLIT"
rc=0
OUT="$TMP/out" "$TMP/fw/build.sh" build > "$TMP/build.log" 2>&1 || rc=$?
grep -E 'dangerous relocation|error:|Error' "$TMP/build.log" | head -5 || true
chroot "$ROOTFS" /opt/esp/shims/xtensa-esp32s3-elf-size -A "$WORK/build/esp-idf/main/crystal_app.o" |
  awk '$1 ~ /^\.(text|literal)/ {k = ($1 ~ /^\.text/) ? "text" : "literal"; s[k] += $2; n++
                                  if ($2 > m) {m = $2; mn = $1}}
       END {printf "crystal_app.o: %d text + %d literal bytes in %d sections, largest %s %d\n",
                   s["text"], s["literal"], n, mn, m}'
if [ $rc -eq 0 ]; then
  chroot "$ROOTFS" /usr/bin/env -i HOME=/root PATH=/usr/bin:/bin IDF_TARGET=esp32s3 IDF_COMPONENT_MANAGER=0 \
    /bin/bash -c ". /opt/esp/esp-idf/export.sh >/dev/null; export PATH=/opt/esp/shims:\$PATH; cd $WORK; idf.py size" |
    grep -E 'IRAM|Flash Code|Flash Data|Total image|DIRAM' || true
  echo "crystal_grow: link OK"
else
  echo "crystal_grow: build FAILED (rc=$rc); log tail:"; tail -5 "$TMP/build.log"
fi
exit $rc
