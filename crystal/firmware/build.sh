#!/bin/sh
# Build the Crystal blink firmware with ESP-IDF inside the Debian rootfs.
#
#   crystal/firmware/build.sh [idf.py args...]      (default: build merge-bin)
#
# The rootfs (ROOTFS, default /opt/debian) needs ESP-IDF at /opt/esp/esp-idf,
# the /proc-free gcc shims at /opt/esp/shims and the patched compiler at
# /opt/crystal-xtensa; see ../toolchain/README.md. The container can't
# bind-mount, so sources are copied in and outputs copied back to ./build/
# (or to $OUT, e.g. OUT=build-test ./build.sh to keep ./build untouched).
# The component manager is disabled: it uses psutil, which needs /proc.
#
# Native mode (ROOTFS=/, e.g. CI on an x86_64 Ubuntu runner): no chroot, no
# copies, no shims. idf.py runs in this directory and builds into ./build.
# It needs IDF_PATH (ESP-IDF v5.4.2 installed with `install.sh esp32s3`),
# CRYSTAL_XTENSA (the patched compiler) and CRYSTAL_LLC_BIN (esp-clang's llc);
# see .github/workflows/firmware.yml.
#
# The outputs include badge-version.txt, "<git describe> <build number>"
# (git rev-list --count HEAD, also compiled in as CR_BUILD). The badge only
# installs an OTA image whose number is greater than its own.
set -eu
ROOTFS=${ROOTFS:-/opt/debian}
HERE=$(cd "$(dirname "$0")" && pwd)
WORK=${WORK:-/build/crystal-firmware}   # path inside the rootfs (override for a second build dir)
[ $# -gt 0 ] || set -- build merge-bin

OUT=${OUT:-$HERE/build}                 # where the outputs are copied

# Version string for the firmware: git describe of this checkout plus the
# build time. Computed here because the chroot copy has no .git.
VER=$(git -C "$HERE" describe --always --dirty --abbrev=7 2>/dev/null || echo unknown)
STAMP=$(date +%H:%M)
# Monotonic build number (commit count): OTA installs only a release whose
# number is greater (main/ota.c; tools/release.sh writes it next to the tag).
# Needs a full clone, not --depth 1.
BUILDNO=$(git -C "$HERE" rev-list --count HEAD 2>/dev/null || echo 0)
printf '// Generated by build.sh; do not edit or commit.\n#define CR_VERSION "%s %s"\n#define CR_BUILD %s\n' \
  "$VER" "$STAMP" "$BUILDNO" > "$HERE/main/version.h"
echo "build.sh: version $VER $STAMP, build $BUILDNO"

# Crystal optimisation / literal placement (main/CMakeLists.txt explains them):
#   CRYSTAL_OPT=--release CRYSTAL_SPLIT=1 ./build.sh
# The chroot gets a clean env, so they go through main/crystal_flags.cmake,
# rewritten only when they change (a change re-runs cmake and Crystal).
FLAGS=$(printf '# Generated by build.sh; do not edit or commit.\nset(CRYSTAL_OPT "%s")\nset(CRYSTAL_SPLIT "%s")\nset(CRYSTAL_LLC_FLAGS "%s")\n' \
  "${CRYSTAL_OPT:-}" "${CRYSTAL_SPLIT:-}" "${CRYSTAL_LLC_FLAGS:-}")
[ "$FLAGS" = "$(cat "$HERE/main/crystal_flags.cmake" 2>/dev/null)" ] ||
  printf '%s\n' "$FLAGS" > "$HERE/main/crystal_flags.cmake"
echo "build.sh: CRYSTAL_OPT='${CRYSTAL_OPT:-}' CRYSTAL_SPLIT='${CRYSTAL_SPLIT:-}' CRYSTAL_LLC_FLAGS='${CRYSTAL_LLC_FLAGS:-}'"

if [ "$ROOTFS" = / ]; then
  # Native: build in place. Same sdkconfig rule as the chroot path below.
  : "${IDF_PATH:?build.sh: native mode (ROOTFS=/) needs IDF_PATH}"
  mkdir -p "$HERE/build"
  if ! cmp -s "$HERE/sdkconfig.defaults" "$HERE/build/sdkconfig.defaults.used"; then
    echo "build.sh: sdkconfig.defaults changed, regenerating sdkconfig"
    rm -f "$HERE/sdkconfig"
  fi
  HERE="$HERE" IDF_TARGET=esp32s3 IDF_COMPONENT_MANAGER=0 bash -c '
    set -e
    . "$IDF_PATH/export.sh" >/dev/null
    cd "$HERE"
    idf.py "$@"
  ' idf.py "$@"
  cp "$HERE/sdkconfig.defaults" "$HERE/build/sdkconfig.defaults.used"
  B=$HERE/build
else
  mkdir -p "$ROOTFS$WORK"
  # idf.py only applies sdkconfig.defaults when it creates sdkconfig, so a
  # changed defaults file would be silently ignored by the persistent build
  # dir. Regenerate sdkconfig whenever the defaults change.
  if ! cmp -s "$HERE/sdkconfig.defaults" "$ROOTFS$WORK/sdkconfig.defaults"; then
    echo "build.sh: sdkconfig.defaults changed, regenerating sdkconfig"
    rm -f "$ROOTFS$WORK/sdkconfig"
  fi
  rm -rf "$ROOTFS$WORK/main" "$ROOTFS$WORK/src" "$ROOTFS$WORK/components"
  cp -a "$HERE/CMakeLists.txt" "$HERE/sdkconfig.defaults" "$HERE/partitions.csv" "$HERE/main" "$HERE/src" "$ROOTFS$WORK/"
  [ -d "$HERE/components" ] && cp -a "$HERE/components" "$ROOTFS$WORK/"

  chroot "$ROOTFS" /usr/bin/env -i HOME=/root TERM=dumb LANG=C.UTF-8 \
    PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin \
    IDF_TARGET=esp32s3 IDF_COMPONENT_MANAGER=0 /bin/bash -c "
      set -e
      . /opt/esp/esp-idf/export.sh >/dev/null
      # Espressif's xtensa-esp32s3-elf-* wrappers need /proc/self/exe; use shell shims.
      export PATH=/opt/esp/shims:\$PATH
      cd $WORK
      idf.py $*
    "
  B="$ROOTFS$WORK/build"
fi

mkdir -p "$OUT"
printf '%s %s\n' "$VER" "$BUILDNO" > "$OUT/badge-version.txt"   # as release.sh writes it
for f in merged-binary.bin crystal_blink.bin crystal_blink.elf crystal_blink.map flash_args \
         bootloader/bootloader.bin partition_table/partition-table.bin ota_data_initial.bin; do
  [ -f "$B/$f" ] || continue
  [ "$B/$f" -ef "$OUT/$(basename "$f")" ] || cp "$B/$f" "$OUT/$(basename "$f")"
done
ls -l "$OUT"
